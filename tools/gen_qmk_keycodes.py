#!/usr/bin/env python3
"""Generate src/qmk/keycodes_table.rs from QMK's keycode data.

    python3 tools/gen_qmk_keycodes.py /path/to/qmk_firmware > src/qmk/keycodes_table.rs

Needs a QMK checkout and its Python requirements (hjson). The table is the "latest" keycode
spec, which is what VIA protocol 12 firmware (QMK 0.20, 2023, and later) uses.
"""
import sys

sys.path.insert(0, sys.argv[1] + "/lib/python")
import os
os.chdir(sys.argv[1])
from qmk.keycodes import load_spec  # noqa: E402

spec = load_spec("latest")
rows = []
for code, v in sorted(spec["keycodes"].items(), key=lambda kv: int(kv[0], 16)):
    aliases = v.get("aliases", [])
    # QMK's main alias (the first one), skipping placeholders like _______ / XXXXXXX
    names = [a for a in aliases if not a.startswith("_") and not a.startswith("XXX")]
    short = names[0] if names else v["key"]
    label = v.get("label", "")
    rows.append((int(code, 16), v["key"], short, label, v.get("group", ""), aliases))

def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

print("// Generated by tools/gen_qmk_keycodes.py from QMK's keycode spec", spec.get("version", ""), "- do not edit.")
print("use super::keycodes::Kc;")
print("#[rustfmt::skip]")
print("pub static KEYCODES: &[Kc] = &[")
for code, key, short, label, group, aliases in rows:
    al = ", ".join(q(a) for a in aliases)
    print(f"    Kc {{ code: 0x{code:04X}, name: {q(key)}, short: {q(short)}, label: {q(label)}, group: {q(group)}, aliases: &[{al}] }},")
print("];")
